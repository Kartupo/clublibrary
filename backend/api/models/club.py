from sqlalchemy import Computed

from ..extensions import db


class Club(db.Model):
    """A club or project team; both work the same way (T-06, T-07, T-09)."""

    __tablename__ = "clubs"

    id = db.Column(db.Integer, primary_key=True)
    name = db.Column(db.String(150), unique=True, nullable=False)
    kind = db.Column(db.Enum("club", "project_team", name="club_kind"), nullable=False)
    category = db.Column(db.String(50), nullable=False, index=True)  # used by Discover filters
    description = db.Column(db.Text)
    logo_url = db.Column(db.String(500))  # Cloudinary URL
    contact_info = db.Column(db.String(255))

    # Approval by a Platform Administrator (T-06, T-07)
    status = db.Column(
        db.Enum("pending", "approved", "rejected", name="club_status"),
        nullable=False,
        default="pending",
        server_default="pending",
        index=True,
    )
    rejection_reason = db.Column(db.String(500))
    requested_by_id = db.Column(db.Integer, db.ForeignKey("users.id", ondelete="SET NULL"))
    reviewed_by_id = db.Column(db.Integer, db.ForeignKey("users.id", ondelete="SET NULL"))
    reviewed_at = db.Column(db.DateTime)
    created_at = db.Column(db.DateTime, nullable=False, server_default=db.func.now())

    memberships = db.relationship("Membership", back_populates="club", cascade="all, delete-orphan")

    def __repr__(self):
        return f"<Club {self.name} ({self.status})>"


class Membership(db.Model):
    """A user's role in one club or team (T-08, T-10). Students without a row are non-members."""

    __tablename__ = "memberships"
    __table_args__ = (
        db.UniqueConstraint("user_id", "club_id", name="uq_membership_user_club"),
        # One Captain per club: captain_flag is 1 only on the Captain's row and NULL
        # for everyone else; NULLs never clash in a unique index
        db.UniqueConstraint("captain_flag", "club_id", name="uq_membership_one_captain"),
    )

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    club_id = db.Column(db.Integer, db.ForeignKey("clubs.id", ondelete="CASCADE"), nullable=False)
    role = db.Column(
        db.Enum("member", "manager", "captain", name="membership_role"),
        nullable=False,
        default="member",
        server_default="member",
    )
    joined_at = db.Column(db.DateTime, nullable=False, server_default=db.func.now())

    # Generated by the database from role only (1 for the Captain, NULL otherwise).
    # It must not use club_id: MySQL rejects generated columns based on a column
    # that has a foreign key with ON DELETE CASCADE. Never set it in code.
    captain_flag = db.Column(
        db.SmallInteger,
        Computed("CASE WHEN role = 'captain' THEN 1 END", persisted=True),
    )

    user = db.relationship("User", back_populates="memberships")
    club = db.relationship("Club", back_populates="memberships")


class MembershipRequest(db.Model):
    """A student's request to join; a Captain or Manager approves or rejects it (T-10)."""

    __tablename__ = "membership_requests"

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    club_id = db.Column(db.Integer, db.ForeignKey("clubs.id", ondelete="CASCADE"), nullable=False)
    status = db.Column(
        db.Enum("pending", "approved", "rejected", name="membership_request_status"),
        nullable=False,
        default="pending",
        server_default="pending",
    )
    decided_by_id = db.Column(db.Integer, db.ForeignKey("users.id", ondelete="SET NULL"))
    decided_at = db.Column(db.DateTime)
    created_at = db.Column(db.DateTime, nullable=False, server_default=db.func.now())


class Follow(db.Model):
    """A user following a club without being a member (T-11)."""

    __tablename__ = "follows"

    user_id = db.Column(db.Integer, db.ForeignKey("users.id", ondelete="CASCADE"), primary_key=True)
    club_id = db.Column(db.Integer, db.ForeignKey("clubs.id", ondelete="CASCADE"), primary_key=True)
    created_at = db.Column(db.DateTime, nullable=False, server_default=db.func.now())
